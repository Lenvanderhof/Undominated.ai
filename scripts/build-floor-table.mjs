#!/usr/bin/env node
/**
 * "What the cheapest model at a capability floor costs, over time."
 *
 * WHY THIS AND NOT A PRICE CHART. Everyone publishes today's prices, so a table
 * of them is a commodity. Nobody publishes what the CHEAPEST model clearing a
 * fixed quality bar costs, tracked across dated snapshots — and that is the only
 * series that answers "is capability actually getting cheaper?" rather than "did
 * this SKU get discounted?".
 *
 * It is also the one asset here that compounds: every day the archive grows, the
 * series gets longer, and it cannot be back-filled by a competitor who starts
 * tomorrow. `data/series-floors.toml` in the build repo is append-only for that
 * reason — "editing retroactively is how a series becomes marketing, and it is
 * detectable from git".
 *
 * Measured on the day this was written: the 1400-Elo floor went $0.0611 →
 * $0.1097 in twelve days, +80%, on the SAME model. Frontier-grade capability got
 * dearer over the observation window. That finding is the section's whole point,
 * and it is the opposite of what the market says.
 *
 *   node scripts/build-floor-table.mjs          # rewrite the table in README.md
 *   node scripts/build-floor-table.mjs --check  # exit 1 if stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const README = resolve(ROOT, 'README.md')
const ORIGIN = 'https://undominated.ai'
const START = '<!--floors-->'
const END = '<!--/floors-->'

const check = process.argv.includes('--check')

const res = await fetch(`${ORIGIN}/data/series/price-at-floor.json`, {
  headers: { accept: 'application/json' },
})
if (!res.ok) throw new Error(`price-at-floor.json returned ${res.status}`)
const series = await res.json()

const money = (v) => `$${v < 1 ? v.toFixed(4).replace(/0+$/, '').replace(/\.$/, '') : v.toFixed(2)}`

const rows = []
for (const floor of series.floors ?? []) {
  const points = floor.points ?? []
  if (points.length < 2) continue
  const first = points[0]
  const last = points[points.length - 1]
  const move = Math.round((100 * (last.price - first.price)) / first.price)
  // A move of zero is a finding too: the cheapest way to clear that bar did not
  // change all window. Say so rather than dropping the row.
  const arrow = move > 0 ? `+${move}%` : move < 0 ? `${move}%` : 'unchanged'
  rows.push(
    `| **≥ ${floor.threshold}** | ${money(first.price)} | ${money(last.price)} | ${arrow} | \`${last.slug}\` |`,
  )
}
if (!rows.length) throw new Error('no floor has two dated points yet — refusing to publish a one-point trend')

const dates = series.dates ?? []
const table = [
  START,
  '',
  `| Capability floor (LMArena) | ${dates[0]} | ${dates[dates.length - 1]} | Move | Cheapest today |`,
  '|:---|---:|---:|---:|:---|',
  ...rows,
  '',
  `<sub>Effective $/M on the balanced workload, from ${dates.length} dated snapshots. Generated by \`scripts/build-floor-table.mjs\`. The floors are append-only — a threshold is never edited in place, because a moved goalpost turns a series into marketing.</sub>`,
  '',
  END,
].join('\n')

const source = readFileSync(README, 'utf8')
const pattern = new RegExp(`${START}[\\s\\S]*?${END}`)
if (!pattern.test(source)) throw new Error(`README has no ${START} … ${END} block`)
const next = source.replace(pattern, table)

if (check) {
  if (next !== source) {
    console.error('the floor table is stale — run: node scripts/build-floor-table.mjs')
    process.exit(1)
  }
  console.log(`floor table agrees with ${ORIGIN} (${rows.length} floors, ${dates.length} snapshots)`)
  process.exit(0)
}

writeFileSync(README, next)
console.log(`floor table written: ${rows.length} floors across ${dates.length} snapshots (${dates[0]} → ${dates[dates.length - 1]})`)
